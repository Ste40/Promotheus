args<-commandArgs(TRUE);root<-normalizePath(if(length(args)) args[1] else '.');source(file.path(root,'Scripts/RNA-Seq/merge_operons_table.R'))
t<-tempfile();dir.create(t);org<-file.path(t,'Toy');dir.create(org);tabs<-file.path(t,'tabs');dir.create(tabs)
op<-function(genes)data.frame(Start=1,Stop=100,Strand='+',`Number of Genes`=2,Genes=genes,check.names=FALSE)
write.table(op('A, B'),file.path(org,'GSE1 Toy_operons.txt'),sep='\t',row.names=FALSE)
write.table(op('B, C'),file.path(org,'GSE2 Toy_operons.txt'),sep='\t',row.names=FALSE)
write.table(op('A, B'),file.path(org,'Toy_operons_mode.txt'),sep='\t',row.names=FALSE)
for(g in c('GSE1','GSE2'))write.table(data.frame(GeneID=c('A','B','C'),n.genes='WAITING_FOR_OPERONS_TABLE'),file.path(tabs,paste(g,'Toy full_tab.txt')),sep='\t',row.names=FALSE)
merge_operons(org,tabs,file.path(org,'GSE2 Toy'),'GSE2','Toy')
a<-read.delim(file.path(tabs,'GSE1 Toy full_tab.txt'))
print(a)
stopifnot(grepl('first gene in operon (mode)',a$n.genes[a$GeneID=='A'],fixed=TRUE),a$n.genes[a$GeneID=='B']=='not first gene in operon')
unlink(t,recursive=TRUE)

cat("PASS: each GSE keeps its own operon annotations and consensus leaders are recognized\n")
# Cached mode must not prevent exporting subsequent GSE tables.
source(file.path(root,'Scripts/RNA-Seq/Operons_detection.R'))
str_replace_all <- stringr::str_replace_all
z<-tempfile();dir.create(z);org<-file.path(z,'Toy');dir.create(org)
g<-file.path(org,'GSE3 Toy');dir.create(g)
write.table(op('A, B'),file.path(org,'Toy_operons_mode.txt'),sep='\t',row.names=FALSE)
write.table(op('B, C'),file.path(g,'_operons.txt'),sep='\t',row.names=FALSE)
stopifnot(Operons_detection(org,1,1000,character(),g,data.frame(Groups='1'),2,data.frame(m.o.name='Toy',GSE=3),'GSE3','Toy'))
stopifnot(file.exists(file.path(org,'GSE3 Toy_operons.txt')))
unlink(z,recursive=TRUE)
cat("PASS: cached consensus preserves later per-GSE operon tables\n")
# More cached GSEs than the requested threshold must still create the mode.
z<-tempfile();dir.create(z);org<-file.path(z,'Toy');dir.create(org)
for (id in 1:3) {
 g<-file.path(org,paste0('GSE',id,' Toy'));dir.create(g)
 write.table(op('A, B'),file.path(g,'_operons.txt'),sep='\t',row.names=FALSE)
}
stopifnot(Operons_detection(org,1,1000,character(),g,data.frame(Groups='1'),2,data.frame(m.o.name='Toy',GSE=3),'GSE3','Toy'))
stopifnot(file.exists(file.path(org,'Toy_operons_mode.txt')))
unlink(z,recursive=TRUE)
cat('PASS: threshold reached or exceeded creates consensus\n')
# The leader on the reverse strand is the last listed gene; empty tables are valid.
z<-tempfile();dir.create(z);org<-file.path(z,'Toy');dir.create(org);tabs<-file.path(z,'tabs');dir.create(tabs)
reverse<-op('D, E');reverse$Strand<-'-'
write.table(reverse,file.path(org,'Toy_operons_mode.txt'),sep='\t',row.names=FALSE)
write.table(reverse,file.path(org,'GSE4 Toy_operons.txt'),sep='\t',row.names=FALSE)
write.table(data.frame(GeneID=c('D','E'),n.genes='WAITING_FOR_OPERONS_TABLE'),file.path(tabs,'GSE4 Toy full_tab.txt'),sep='\t',row.names=FALSE)
stopifnot(merge_operons(org,tabs,file.path(org,'GSE4 Toy'),'GSE4','Toy'))
v<-read.delim(file.path(tabs,'GSE4 Toy full_tab.txt'))
stopifnot(v$n.genes[1]=='not first gene in operon',grepl('first gene in operon (mode)',v$n.genes[2],fixed=TRUE))
write.table(reverse[FALSE,],file.path(org,'GSE5 Toy_operons.txt'),sep='\t',row.names=FALSE)
write.table(data.frame(GeneID='Z',n.genes='WAITING_FOR_OPERONS_TABLE'),file.path(tabs,'GSE5 Toy full_tab.txt'),sep='\t',row.names=FALSE)
stopifnot(merge_operons(org,tabs,file.path(org,'GSE5 Toy'),'GSE5','Toy'))
stopifnot(read.delim(file.path(tabs,'GSE5 Toy full_tab.txt'))$n.genes=='gene not in operon')
unlink(z,recursive=TRUE)
cat('PASS: reverse-strand leaders and empty predictions\n')
